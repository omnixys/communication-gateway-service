/**
 * Narrows an unknown JSON value to a string without relying on the default
 * object stringification.
 *
 * Provider payloads and request metadata are untrusted input, so stringifying
 * them directly would leak `[object Object]` into addresses and subjects.
 *
 * @param value untrusted value.
 * @param fallback result for every value that is not a non-empty string.
 */
export function asText(value: unknown, fallback = ''): string {
  if (typeof value === 'string') {
    return value;
  }
  if (typeof value === 'number' || typeof value === 'bigint') {
    return String(value);
  }
  if (typeof value === 'boolean') {
    return value ? 'true' : 'false';
  }
  return fallback;
}

/** Narrows an unknown JSON value to a record, or `null` when it is not one. */
export function asRecord(value: unknown): Record<string, unknown> | null {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

/** Narrows an unknown JSON value to a finite number, or `null`. */
export function asNumber(value: unknown): number | null {
  if (typeof value === 'number' && Number.isFinite(value)) {
    return value;
  }
  if (typeof value === 'string' && value.trim().length > 0) {
    const parsed = Number(value);
    return Number.isFinite(parsed) ? parsed : null;
  }
  return null;
}
